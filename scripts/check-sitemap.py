#!/usr/bin/env python3
"""Validate Hugo's multilingual sitemap index and child sitemaps after a build.

Hugo's built-in multilingual sitemap output is a sitemap index at public/sitemap.xml
plus one sitemap.xml per language. This script deliberately validates the index
instead of overwriting it with a merged urlset.
"""
from __future__ import annotations
from pathlib import Path
from urllib.parse import urlparse
import sys, tomllib, xml.etree.ElementTree as ET
ROOT=Path(__file__).resolve().parents[1]
PUBLIC=ROOT/'public'
LANGS=('de','en','pl','es','pt','ja')
NS='http://www.sitemaps.org/schemas/sitemap/0.9'
def q(tag): return f'{{{NS}}}{tag}'
def fail(msg):
    print('ERROR:',msg,file=sys.stderr); raise SystemExit(1)
def main():
    cfg=tomllib.loads((ROOT/'hugo.toml').read_text(encoding='utf-8'))
    base=cfg.get('baseURL','')
    disabled=set(cfg.get('disableKinds',[]))
    if not {'taxonomy','term'}.issubset(disabled):
        fail("hugo.toml must disable taxonomy and term kinds at the top level; check TOML table scope.")
    baseurl=urlparse(base)
    if baseurl.scheme!='https' or not baseurl.netloc: fail('hugo.toml baseURL must be an absolute HTTPS URL.')
    root_file=PUBLIC/'sitemap.xml'
    if not root_file.exists(): fail('public/sitemap.xml missing; run hugo --cleanDestinationDir first.')
    try: index=ET.parse(root_file).getroot()
    except ET.ParseError as e: fail(f'Invalid XML in public/sitemap.xml: {e}')
    if index.tag!=q('sitemapindex'):
        fail('public/sitemap.xml should be Hugo’s multilingual sitemapindex. Do not replace it with a merged urlset.')
    locs=[]
    for node in index.findall(q('sitemap')):
        loc=(node.findtext(q('loc')) or '').strip()
        if not loc: fail('Sitemap index contains an empty <loc>.')
        parsed=urlparse(loc)
        if parsed.hostname in {'localhost', '127.0.0.1', '::1'} or parsed.scheme == 'http':
            fail('The generated sitemap contains local/development URLs ('+loc+'). Stop `hugo server` with Ctrl+C, run `hugo --cleanDestinationDir`, then rerun `py -3 scripts\\check-sitemap.py`. Do not run the sitemap audit against output last generated by `hugo server`.')
        if parsed.scheme!='https' or parsed.netloc.lower()!=baseurl.netloc.lower(): fail(f'Unexpected sitemap URL: {loc}; expected HTTPS URLs on {baseurl.netloc}')
        locs.append(loc)
    if len(locs)!=len(LANGS): fail(f'Sitemap index has {len(locs)} child sitemaps; expected exactly {len(LANGS)} (one per locale).')
    # Check that all configured language sitemap endpoints are listed and each urlset is valid.
    langs_found=set(); total=0; all_pages=set(); counts={lang:0 for lang in LANGS}
    for loc in locs:
        parsed=urlparse(loc); path=parsed.path.strip('/')
        parts=path.split('/')
        if len(parts)>=2 and parts[-1]=='sitemap.xml' and parts[-2] in LANGS:
            child_lang=parts[-2]
            if child_lang in langs_found: fail(f'Multiple child sitemaps found for locale {child_lang}.')
            langs_found.add(child_lang)
        else:
            fail(f'Unexpected child sitemap path in multilingual index: {loc}')
        local_path=PUBLIC.joinpath(*parts)
        if not local_path.is_file(): fail(f'Indexed child sitemap does not exist locally: {local_path.relative_to(ROOT)} ({loc})')
        try: sm=ET.parse(local_path).getroot()
        except ET.ParseError as e: fail(f'Invalid child sitemap {loc}: {e}')
        if sm.tag!=q('urlset'): fail(f'Child is not a urlset: {loc}')
        for item in sm.findall(q('url')):
            url=(item.findtext(q('loc')) or '').strip()
            if not url: fail(f'Empty URL in child sitemap {loc}')
            u=urlparse(url)
            if any(part.casefold() in {'categories','tags'} for part in u.path.strip('/').split('/')):
                fail(f'Taxonomy archive URL must not be published in the sitemap: {url}')
            if u.scheme!='https' or u.netloc.lower()!=baseurl.netloc.lower(): fail(f'Off-domain or non-HTTPS URL in sitemap: {url}')
            if url in all_pages: fail(f'Duplicate URL across child sitemaps: {url}')
            all_pages.add(url); total+=1
            if len(parts)>=2 and parts[-2] in LANGS:
                counts[parts[-2]]+=1
    # Some Hugo configurations may not prefix the default-language sitemap path.
    # In that case, still require five explicit translated sitemap paths and six total children.
    missing=set(LANGS)-langs_found
    if missing: fail('Missing language sitemap paths for: '+', '.join(sorted(missing)))
    if any(counts[lang]==0 for lang in LANGS): fail('At least one locale sitemap contains no page URLs.')
    if len(all_pages)==0: fail('No page URLs found in child sitemaps.')
    print('Per-locale sitemap URL counts: '+', '.join(f'{lang}={counts[lang]}' for lang in LANGS))
    print(f'PASS: multilingual sitemap index includes {len(locs)} child sitemap(s), all six locales found, {total} unique HTTPS page URLs; taxonomy archives excluded.')
    print('The root sitemap remains a sitemapindex, as required for this Hugo multilingual build; no file was overwritten.')
if __name__=='__main__': main()
